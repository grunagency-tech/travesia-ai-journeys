export const getSmartImage = (query: string): string => {
    const q = query.toLowerCase().trim();

    // 1. Direct match
    if (DESTINATION_IMAGES[q]) return DESTINATION_IMAGES[q];

    // 2. Best partial match (Longest specific key)
    let bestMatchKey = "";

    const keys = Object.keys(DESTINATION_IMAGES);
    for (const key of keys) {
        // If the query contains the key (e.g. "Nueva York, USA" contains "Nueva York")
        // OR the key contains the query (e.g. "Nueva York" contains "york" - less likely usage)
        if (q.includes(key)) {
            // We want the longest key that matches. 
            // e.g. "Nueva York" (10 chars) > "USA" (3 chars)
            if (key.length > bestMatchKey.length) {
                bestMatchKey = key;
            }
        }
    }

    if (bestMatchKey) return DESTINATION_IMAGES[bestMatchKey];

    return DESTINATION_IMAGES['city']; // Ultimate fallback
};
